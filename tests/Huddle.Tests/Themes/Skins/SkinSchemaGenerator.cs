using System.Text;
using System.Text.Json;
using Agency.Huddle.App.Themes.Skins;

namespace Agency.Huddle.Tests.Themes.Skins;

/// <summary>
/// Generates <c>skin.schema.json</c> from the skin model and the token registry, so an editor validates a skin file
/// against exactly what <see cref="SkinLoader"/> accepts. <see cref="SkinSchemaTests"/> compares the generated text to the
/// file on disk and rewrites it on request.
/// </summary>
internal static class SkinSchemaGenerator
{
    /// <summary>Builds the schema text, with LF line endings and a trailing newline.</summary>
    /// <returns>The JSON Schema (draft 2020-12) for one skin file.</returns>
    public static string Generate()
    {
        using MemoryStream stream = new();
        using (Utf8JsonWriter json = new(stream, new JsonWriterOptions { Indented = true, NewLine = "\n" }))
        {
            json.WriteStartObject();
            json.WriteString("$schema", "https://json-schema.org/draft/2020-12/schema");
            json.WriteString("title", "Huddle skin");
            json.WriteString("description", "One Theme and mode. Generated by SkinSchemaGenerator; do not edit by hand.");
            json.WriteString("type", "object");
            json.WriteBoolean("additionalProperties", false);
            json.WriteStartArray("required");
            foreach (string name in (string[])["id", "label", "mode", "order"])
            {
                json.WriteStringValue(name);
            }

            json.WriteEndArray();
            json.WriteStartObject("properties");
            WriteType(json, "$schema", "string");
            WriteType(json, "id", "string");
            WriteType(json, "label", "string");
            json.WriteStartObject("mode");
            json.WriteStartArray("enum");
            json.WriteStringValue("light");
            json.WriteStringValue("dark");
            json.WriteEndArray();
            json.WriteEndObject();
            WriteType(json, "order", "integer");
            WriteType(json, "include", "string");
            WriteType(json, "radius", "string");
            WriteType(json, "pack", "string");
            WriteFaces(json);
            WriteTypography(json);
            WriteShadows(json);
            WritePalette(json);
            WriteTokens(json);
            WriteTraits(json);
            json.WriteEndObject();
            json.WriteEndObject();
        }

        return Encoding.UTF8.GetString(stream.ToArray()) + "\n";
    }

    private static void WriteType(Utf8JsonWriter json, string name, string type)
    {
        json.WriteStartObject(name);
        json.WriteString("type", type);
        json.WriteEndObject();
    }

    private static void WriteFaces(Utf8JsonWriter json)
    {
        json.WriteStartObject("faces");
        json.WriteString("type", "object");
        json.WriteBoolean("additionalProperties", false);
        json.WriteStartObject("properties");
        foreach (string face in (string[])["ui", "read", "mono"])
        {
            json.WriteStartObject(face);
            json.WriteString("type", "array");
            json.WriteStartObject("items");
            json.WriteString("type", "string");
            json.WriteString("pattern", "^[A-Za-z0-9 -]+$");
            json.WriteEndObject();
            json.WriteEndObject();
        }

        json.WriteEndObject();
        json.WriteEndObject();
    }

    private static void WriteTypography(Utf8JsonWriter json)
    {
        json.WriteStartObject("typography");
        json.WriteString("type", "object");
        json.WriteBoolean("additionalProperties", false);
        json.WriteStartObject("properties");
        WriteType(json, "letterSpacing", "string");
        WriteType(json, "lineHeight", "string");
        json.WriteEndObject();
        json.WriteEndObject();
    }

    private static void WriteShadows(Utf8JsonWriter json)
    {
        json.WriteStartObject("shadows");
        json.WriteString("type", "object");
        json.WriteString("description", $"Keys are \"N\" or \"N-M\" with {SkinLoader.FirstElevation} <= N <= M <= {SkinLoader.LastElevation}, without overlaps. Values are literal shadows.");
        json.WriteStartObject("patternProperties");
        json.WriteStartObject(@"^\d+(-\d+)?$");
        json.WriteString("type", "string");
        json.WriteEndObject();
        json.WriteEndObject();
        json.WriteBoolean("additionalProperties", false);
        json.WriteEndObject();
    }

    private static void WritePalette(Utf8JsonWriter json)
    {
        json.WriteStartObject("palette");
        json.WriteString("type", "object");
        json.WriteBoolean("additionalProperties", false);
        json.WriteStartObject("properties");
        foreach (string key in SkinLoader.PaletteKeys)
        {
            json.WriteStartObject(key);
            json.WriteString("type", "string");
            json.WriteString("pattern", @"^(#[0-9a-fA-F]{3,8}|rgba?\([0-9 ,.%]+\))$");
            json.WriteEndObject();
        }

        json.WriteEndObject();
        json.WriteEndObject();
    }

    private static void WriteTokens(Utf8JsonWriter json)
    {
        json.WriteStartObject("tokens");
        json.WriteString("type", "object");
        json.WriteBoolean("additionalProperties", false);
        json.WriteStartObject("properties");
        foreach (Token token in SkinTokens.All)
        {
            json.WriteStartObject(token.Key);
            json.WriteString("type", "string");
            json.WriteString("description", token.Description);
            json.WriteEndObject();
        }

        json.WriteEndObject();
        json.WriteEndObject();
    }

    private static void WriteTraits(Utf8JsonWriter json)
    {
        json.WriteStartObject("traits");
        json.WriteString("type", "object");
        json.WriteBoolean("additionalProperties", false);
        json.WriteStartObject("properties");
        foreach (KeyValuePair<string, IReadOnlyList<string>> trait in SkinLoader.TraitValues)
        {
            json.WriteStartObject(trait.Key);
            json.WriteStartArray("enum");
            foreach (string value in trait.Value)
            {
                json.WriteStringValue(value);
            }

            json.WriteEndArray();
            json.WriteEndObject();
        }

        json.WriteEndObject();
        json.WriteEndObject();
    }
}
